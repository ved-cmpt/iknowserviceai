"""Enumerations: the single source of truth for values stored as VARCHAR + CHECK (ADR-006)."""

from enum import StrEnum


class Role(StrEnum):
    USER = "USER"
    AGENT = "AGENT"
    ADMIN = "ADMIN"


class Category(StrEnum):
    ACCOUNT_ACCESS = "ACCOUNT_ACCESS"
    SOFTWARE = "SOFTWARE"
    HARDWARE = "HARDWARE"
    NETWORK = "NETWORK"
    OTHER = "OTHER"


class Priority(StrEnum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    URGENT = "URGENT"


class RequestStatus(StrEnum):
    NEW = "NEW"
    ANALYZING = "ANALYZING"
    TRIAGED = "TRIAGED"
    NEEDS_HUMAN_REVIEW = "NEEDS_HUMAN_REVIEW"
    IN_PROGRESS = "IN_PROGRESS"
    RESOLVED = "RESOLVED"
    CLOSED = "CLOSED"


class ArticleStatus(StrEnum):
    DRAFT = "DRAFT"
    PUBLISHED = "PUBLISHED"
    ARCHIVED = "ARCHIVED"


class AiRunStatus(StrEnum):
    STARTED = "STARTED"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"


class AiMode(StrEnum):
    MOCK = "MOCK"
    GEMINI = "GEMINI"


class ReviewState(StrEnum):
    NOT_REQUIRED = "NOT_REQUIRED"
    PENDING_REVIEW = "PENDING_REVIEW"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"


class EventType(StrEnum):
    REQUEST_CREATED = "REQUEST_CREATED"
    ASSIGNED = "ASSIGNED"
    UNASSIGNED = "UNASSIGNED"
    PRIORITY_CHANGED = "PRIORITY_CHANGED"
    CATEGORY_CHANGED = "CATEGORY_CHANGED"
    STATUS_CHANGED = "STATUS_CHANGED"
    COMMENT_ADDED = "COMMENT_ADDED"
    # Hidden from requesters: they are absent from REQUESTER_EVENT_DETAILS (ADR-014).
    AI_ANALYSIS_STARTED = "AI_ANALYSIS_STARTED"
    AI_ANALYSIS_SUCCEEDED = "AI_ANALYSIS_SUCCEEDED"
    AI_ANALYSIS_FAILED = "AI_ANALYSIS_FAILED"
    SUGGESTION_REVIEWED = "SUGGESTION_REVIEWED"
    SUGGESTION_WITHHELD = "SUGGESTION_WITHHELD"
    FEEDBACK_ADDED = "FEEDBACK_ADDED"


class RiskFlag(StrEnum):
    """The allow-list for `risk_flags`. A model returning anything else is invalid output."""

    # Hard review signals. The deterministic policy scan sets these, and so may a model.
    ACCOUNT_COMPROMISE = "ACCOUNT_COMPROMISE"
    CREDENTIAL_REQUEST = "CREDENTIAL_REQUEST"
    PHISHING = "PHISHING"
    PRIVACY_SENSITIVE = "PRIVACY_SENSITIVE"
    PAYMENT = "PAYMENT"
    PRIVILEGED_ACCESS = "PRIVILEGED_ACCESS"
    ACCOUNT_RECOVERY = "ACCOUNT_RECOVERY"
    DEVICE_WIPE = "DEVICE_WIPE"
    DESTRUCTIVE_ACTION = "DESTRUCTIVE_ACTION"
    PROMPT_INJECTION = "PROMPT_INJECTION"
    # Set by the server from validation and from scanning the model's output.
    INVALID_CITATION = "INVALID_CITATION"
    NO_CITATIONS = "NO_CITATIONS"
    NO_RELEVANT_KNOWLEDGE = "NO_RELEVANT_KNOWLEDGE"
    LOW_CONFIDENCE = "LOW_CONFIDENCE"
    MODEL_REQUESTED_REVIEW = "MODEL_REQUESTED_REVIEW"
    OUTPUT_ASKS_CREDENTIALS = "OUTPUT_ASKS_CREDENTIALS"
    OUTPUT_CLAIMS_ACTION = "OUTPUT_CLAIMS_ACTION"
    OUTPUT_UNSUPPORTED_CONTACT = "OUTPUT_UNSUPPORTED_CONTACT"
    KB_CONTENT_SUSPECT = "KB_CONTENT_SUSPECT"
